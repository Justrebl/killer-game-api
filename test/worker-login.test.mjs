import assert from "node:assert/strict";
import test from "node:test";
import worker from "../worker/src/index.js";
import { buildSeed } from "../worker/scripts/seed-lib.mjs";

function makeLoginDatabase(event, targets = []) {
  const sessions = [];
  const rateLimits = new Map();
  return {
    sessions,
    prepare(sql) {
      let args = [];
      const statement = {
        bind(...values) {
          args = values;
          return statement;
        },
        async first() {
          if (sql.includes("SELECT id, credential_verifier")) {
            return {
              id: event.id,
              credential_verifier: event.credentialVerifier,
              auth_salt: event.authSalt,
              kdf_iterations: event.kdfIterations
            };
          }
          if (sql.includes("SELECT encryption_salt")) {
            return {
              encryption_salt: event.encryptionSalt,
              kdf_iterations: event.kdfIterations
            };
          }
          if (sql.includes("SELECT window_start")) return rateLimits.get(args[0]) ?? null;
          return null;
        },
        async all() {
          if (sql.includes("FROM targets")) {
            return {
              results: targets.map((target) => ({
                id: target.id,
                name: target.name,
                condition: target.condition,
                victory_id: null,
                completed_at: null,
                photo_key: null
              }))
            };
          }
          return { results: [] };
        },
        async run() {
          if (sql.startsWith("INSERT INTO sessions")) sessions.push(args);
          if (sql.startsWith("INSERT INTO rate_limits")) {
            rateLimits.set(args[0], { window_start: args[1], attempts: args[2] });
          }
          return { success: true };
        }
      };
      return statement;
    }
  };
}

test("Worker login authenticates a verifier generated by the seed builder", async () => {
  const seed = await buildSeed(
    {
      eventId: "event-test",
      killer: "Pierrot",
      password: "test-password-with-length",
      targets: [{ name: "Alice", condition: "Faire rire Bob" }]
    },
    {
      randomBytes: () => Buffer.alloc(16, 1),
      randomUUID: () => "target-test",
      now: "2026-11-20T00:00:00.000Z"
    }
  );
  const database = makeLoginDatabase(seed.event, seed.targets);
  const request = new Request("https://worker.test/api/login", {
    method: "POST",
    headers: {
      Origin: "https://justrebl.github.io",
      "Content-Type": "application/json",
      "CF-Connecting-IP": "192.0.2.1"
    },
    body: JSON.stringify({ credential: "test-password-with-length" })
  });

  const response = await worker.fetch(request, {
    ALLOWED_ORIGIN: "https://justrebl.github.io",
    DB: database,
    PHOTOS: {}
  });

  assert.equal(response.status, 200);
  const body = await response.json();
  assert.match(body.token, /^[0-9a-f-]{36}$/);
  assert.equal(body.session.kdfIterations, 100000);
  assert.equal(body.session.targets[0].name, "Alice");
  assert.equal(body.session.targets[0].photoPresent, false);
  assert.equal("photo_key" in body.session.targets[0], false);
  assert.equal(database.sessions.length, 1);
});

test("Worker rejects a stored iteration count above the deployment limit", async () => {
  const database = makeLoginDatabase({
    id: "event-test",
    credentialVerifier: "unused",
    authSalt: Buffer.alloc(16).toString("base64"),
    encryptionSalt: Buffer.alloc(16).toString("base64"),
    kdfIterations: 100001
  });
  const request = new Request("https://worker.test/api/login", {
    method: "POST",
    headers: {
      Origin: "https://justrebl.github.io",
      "Content-Type": "application/json"
    },
    body: JSON.stringify({ credential: "test-password-with-length" })
  });

  const response = await worker.fetch(request, {
    ALLOWED_ORIGIN: "https://justrebl.github.io",
    DB: database,
    PHOTOS: {}
  });

  assert.equal(response.status, 503);
  assert.equal(database.sessions.length, 0);
});
